#   - generate_charuco_board.py: Generate printable Charuco calibration board
#   - annotate_charuco_board.py: Add measurement annotations to board image
#
# Usage:
#   conda activate gmr
#   cd TWIST2
#   python deploy_real/utils/<script_name>.py
